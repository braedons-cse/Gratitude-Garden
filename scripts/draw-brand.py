"""Draw the app's icon and store graphics from the garden's own flower (roadmap 0.7).

The mark is the mature plant from ui/sprites/GgSprites.kt (drawMaturePlant): six leaves,
five petals and a centre, in the Tulip palette. This script holds that geometry once and
writes everything that shows it:

  app/src/main/res/drawable/ic_launcher_foreground.xml   adaptive icon, full colour
  app/src/main/res/drawable/ic_launcher_monochrome.xml   themed icon (Android 13+)
  docs/store/icon-512.png                                Play Console's app icon
  docs/store/feature-graphic.png                         Play Console's 1024x500 banner
  docs/store/screenshots/*.png                           the phone screenshots, framed

The screenshots are framed from the emulator captures in docs/store/screenshots/raw/ (see
docs/play-listing.md for how they were taken): 1080x1920 with a caption, because Play
refuses a screenshot more than twice as long as it is wide, and a 1080x2400 phone is 2.22.

Change the plant in GgSprites.kt and here together. Needs Pillow:

  python scripts/draw-brand.py
"""
import math
import os
from dataclasses import dataclass

from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "app", "src", "main", "res")
STORE = os.path.join(ROOT, "docs", "store")
FONTS = os.path.join(RES, "font")

# ui/theme/Color.kt and PlantPalette.
SAGE = "#E8F0E2"
MOSS = "#C9D9B8"
PRIMARY_DEEP = "#3E5F33"
INK_SOFT = "#5C6B58"
TULIP = ("#E85D75", "#A8324A", "#6B9B47")  # bloom, centre, leaf
SUNFLOWER = ("#F4C542", "#8B5A2B", "#5C8A4D")
LAVENDER = ("#9B7BC9", "#6B4D8C", "#7BA85C")


@dataclass
class Oval:
    """An ellipse centred at (cx, cy), turned [rotation] degrees clockwise about [pivot]."""
    cx: float
    cy: float
    rx: float
    ry: float
    rotation: float
    pivot: tuple
    color: str
    role: str  # leaf, petal or centre


def mature_plant(cx, cy, s, palette):
    """drawMaturePlant for a box of side [s] centred at (cx, cy), back to front."""
    bloom, centre, leaf = palette
    shapes = []
    lf = s * 0.38
    w, h = lf * 0.75, lf * 1.1
    for deg in (0, 60, 120, 180, 240, 300):
        # topLeft.y = c - h*0.85, so the oval's centre sits h*0.35 above c.
        shapes.append(Oval(cx, cy - h * 0.85 + h / 2, w / 2, h / 2, deg, (cx, cy), leaf, "leaf"))
    bloom_size = s * 0.6
    petal = bloom_size * 0.52 / 2
    for deg in (0, 72, 144, 216, 288):
        shapes.append(Oval(cx, cy - bloom_size * 0.22, petal, petal, deg, (cx, cy), bloom, "petal"))
    r = bloom_size * 0.42 / 2
    shapes.append(Oval(cx, cy, r, r, 0, (cx, cy), centre, "centre"))
    return shapes


# The adaptive icon is 108 units with the mark inside the 66-unit safe circle: the leaf tips
# reach 0.355 s from the centre, so s = 86 keeps them at 30.5, with a margin inside it.
ICON_SIZE = 108
ICON_PLANT = 86


def fmt(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def oval_path(o):
    left, right = o.cx - o.rx, o.cx + o.rx
    a = f"A{fmt(o.rx)},{fmt(o.ry)} 0 1,0"
    return f"M{fmt(left)},{fmt(o.cy)} {a} {fmt(right)},{fmt(o.cy)} {a} {fmt(left)},{fmt(o.cy)} Z"


def vector(shapes, fill_for, comment):
    out = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- {comment} Generated by scripts/draw-brand.py; edit that, not this. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="108dp"',
        '    android:height="108dp"',
        '    android:viewportWidth="108"',
        '    android:viewportHeight="108">',
    ]
    for o in shapes:
        color, alpha = fill_for(o)
        attrs = f'android:fillColor="{color}"'
        if alpha < 1:
            attrs += f' android:fillAlpha="{alpha}"'
        path = f'<path {attrs} android:pathData="{oval_path(o)}" />'
        if o.rotation:
            out.append(
                f'    <group android:rotation="{o.rotation}" '
                f'android:pivotX="{fmt(o.pivot[0])}" android:pivotY="{fmt(o.pivot[1])}">'
            )
            out.append(f"        {path}")
            out.append("    </group>")
        else:
            out.append(f"    {path}")
    out.append("</vector>")
    return "\n".join(out) + "\n"


def oval_points(o, steps=180):
    """The ellipse as a polygon, rotated, for Pillow."""
    t = math.radians(o.rotation)
    px, py = o.pivot
    pts = []
    for i in range(steps):
        a = 2 * math.pi * i / steps
        x, y = o.cx + o.rx * math.cos(a) - px, o.cy + o.ry * math.sin(a) - py
        pts.append((px + x * math.cos(t) - y * math.sin(t), py + x * math.sin(t) + y * math.cos(t)))
    return pts


def paint(draw, shapes, scale=1.0):
    for o in shapes:
        draw.polygon([(x * scale, y * scale) for x, y in oval_points(o)], fill=o.color)


SS = 4  # supersampling, for smooth edges


def render(width, height, background, draw_fn):
    img = Image.new("RGB", (width * SS, height * SS), background)
    draw_fn(img, ImageDraw.Draw(img))
    return img.resize((width, height), Image.LANCZOS)


def font(name, size, weight=None):
    f = ImageFont.truetype(os.path.join(FONTS, name), size * SS)
    if weight is not None:
        f.set_variation_by_axes([weight])
    return f


# Raw capture -> caption, in listing order.
CAPTIONS = {
    "01-garden": "Every kind thought\ngrows your garden",
    "02-write": "Type it, say it,\nor add a photo",
    "03-journal": "Look back on the\nlittle things",
    "04-shop": "Spend your coins on\nseeds and scenery",
    "05-level-up": "Level up and unlock\nnew flowers",
    "06-me": "Reminders, streak freezes\nand your journal to keep",
}


def frame(raw_path, caption, out_path):
    w, h = 1080, 1920
    # Moss, a shade darker than the app's sage, so the screen stands out from the page.
    img = Image.new("RGB", (w * SS, h * SS), MOSS)
    d = ImageDraw.Draw(img)
    title = font("caprasimo_regular.ttf", 64)
    d.multiline_text((w / 2 * SS, 190 * SS), caption, font=title, fill=PRIMARY_DEEP,
                     anchor="mm", align="center", spacing=14 * SS)
    shot = Image.open(raw_path).convert("RGB")
    sh = 1540
    sw = round(shot.width * sh / shot.height)
    x, y = (w - sw) // 2, 340
    radius = 44
    # A soft shadow, then the screen with rounded corners.
    shadow = Image.new("L", img.size, 0)
    ImageDraw.Draw(shadow).rounded_rectangle(
        ((x - 2) * SS, (y + 10) * SS, (x + sw + 2) * SS, (y + sh + 14) * SS), radius=radius * SS, fill=70)
    shadow = shadow.filter(ImageFilter.GaussianBlur(18 * SS))
    img.paste(Image.new("RGB", img.size, "#8FA581"), (0, 0), shadow)
    screen = shot.resize((sw * SS, sh * SS), Image.LANCZOS)
    mask = Image.new("L", screen.size, 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, screen.width, screen.height), radius=radius * SS, fill=255)
    img.paste(screen, (x * SS, y * SS), mask)
    img.resize((w, h), Image.LANCZOS).save(out_path)


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote", os.path.relpath(path, ROOT))


def main():
    c = ICON_SIZE / 2
    icon = mature_plant(c, c, ICON_PLANT, TULIP)

    write(
        os.path.join(RES, "drawable", "ic_launcher_foreground.xml"),
        vector(icon, lambda o: (o.color, 1), "The garden's mature tulip, as drawMaturePlant draws it."),
    )
    # Themed icons tint one colour by alpha: the leaves sit back so the bloom reads.
    write(
        os.path.join(RES, "drawable", "ic_launcher_monochrome.xml"),
        vector(
            icon,
            lambda o: ("#FF000000", 0.45 if o.role == "leaf" else 1),
            "Themed-icon layer: one colour, leaves lighter than the bloom.",
        ),
    )

    os.makedirs(STORE, exist_ok=True)

    # Play's icon is a full square that Play masks itself: the adaptive icon's background
    # and foreground, flattened.
    side = 512
    k = side / ICON_SIZE * SS
    png = render(side, side, SAGE, lambda img, d: paint(d, icon, k))
    png.save(os.path.join(STORE, "icon-512.png"))
    print("wrote docs/store/icon-512.png")

    # The banner: a small cluster of the garden's blooms, then the name and the line from
    # the site's landing page.
    def banner(img, d):
        cluster = (
            mature_plant(195, 255, 290, TULIP)
            + mature_plant(352, 158, 150, SUNFLOWER)
            + mature_plant(345, 365, 128, LAVENDER)
        )
        paint(d, cluster, SS)
        left, right = 470, 1024 - 56
        title = font("caprasimo_regular.ttf", 84)
        d.text((left * SS, 228 * SS), "Gratitude", font=title, fill=PRIMARY_DEEP, anchor="ls")
        d.text((left * SS, 316 * SS), "Garden", font=title, fill=PRIMARY_DEEP, anchor="ls")
        # The largest tagline that fits beside the flowers.
        line = "One kind word a day grows a garden."
        size = 34
        while size > 20:
            tagline = font("nunito_variable.ttf", size, weight=600)
            if d.textlength(line, font=tagline) <= (right - left) * SS:
                break
            size -= 1
        d.text(((left + 3) * SS, 372 * SS), line, font=tagline, fill=INK_SOFT, anchor="ls")

    render(1024, 500, SAGE, banner).save(os.path.join(STORE, "feature-graphic.png"))
    print("wrote docs/store/feature-graphic.png")

    shots = os.path.join(STORE, "screenshots")
    for name, caption in CAPTIONS.items():
        raw = os.path.join(shots, "raw", name + ".png")
        if os.path.exists(raw):
            frame(raw, caption, os.path.join(shots, name + ".png"))
            print(f"wrote docs/store/screenshots/{name}.png")


if __name__ == "__main__":
    main()
